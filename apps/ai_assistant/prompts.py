def get_role_based_prompt(context_dict):
    """Generates a dynamic system prompt based on the user's role and data context"""
    role_context = context_dict.get('role_context', '')
    role_type = context_dict.get('role_type', '')
    data_json = context_dict.get('data', {})
    import json
    data_str = json.dumps(data_json, ensure_ascii=False, indent=2)
    
    base_prompt = SYSTEM_PROMPT
    if role_type == 'supplier':
        base_prompt = SUPPLIER_PROMPT
        
    return f"""
{base_prompt}

[TRUSTED_CONTEXT]
{role_context}
{data_str}
[/TRUSTED_CONTEXT]
"""
